/**
 * Retourne la "recette sport du jour" — déterministe par date.
 * Stable dans la journée (changera seulement au passage de minuit).
 * L'index est calculé via le jour de l'année % nombre de recettes.
 */
export function getSportRecipeOfTheDay(date: Date = new Date()): SportRecipe {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const dayOfYear = Math.floor(diff / 86400000);
  return SPORT_RECIPES[dayOfYear % SPORT_RECIPES.length];
}

/** Récupère une recette par son ID. Null si pas trouvée. */
export function getSportRecipeById(id: string): SportRecipe | null {
  return SPORT_RECIPES.find((r) => r.id === id) ?? null;
}
